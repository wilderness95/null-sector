import { test, expect } from '@playwright/test';

test('missing character asset shows a loading error instead of invisible enemies', async ({ page }) => {
  await page.route('**/models/RobotExpressive.glb', route => route.abort());
  await page.goto('/');
  await expect(page.locator('#modal-title')).toHaveText('NEM INDULT EL');
  await expect(page.locator('#start')).toBeDisabled();
  await expect(page.locator('#modal-text')).toContainText('karaktermodell');
});

test('desktop starts, locks the mouse, fires, reloads and pauses', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto('/');
  await expect(page.locator('#start')).toBeVisible();
  await page.locator('#seed').fill('TEST-SECTOR');
  await page.screenshot({ path: '/tmp/opencode/null-sector-menu.png' });
  await page.locator('#start').click();
  await expect(page.locator('#hud')).toBeVisible();
  await expect.poll(() => page.evaluate(() => document.pointerLockElement?.id)).toBe('game');
  await expect(page.locator('#enemy-count')).toHaveText('06 / 06');
  await page.mouse.down();
  await page.mouse.up();
  await expect(page.locator('#ammo')).toHaveText('29');
  await page.keyboard.press('r');
  await expect(page.locator('#reload-status')).toHaveText('ÚJRATÖLTÉS...');
  await expect(page.locator('#ammo')).toHaveText('30', { timeout: 10000 });
  await expect(page.locator('#reserve')).toHaveText('119');
  await page.keyboard.down('w');
  await page.waitForTimeout(500);
  await page.keyboard.up('w');
  await page.screenshot({ path: '/tmp/opencode/null-sector-game.png' });
  await page.evaluate(() => document.exitPointerLock());
  await expect(page.locator('#modal-title')).toHaveText('SZÜNET');
  const ammo = await page.locator('#ammo').textContent();
  await page.waitForTimeout(200);
  await expect(page.locator('#ammo')).toHaveText(ammo);
  await expect(page.locator('#modal')).toBeVisible();
  expect(errors).toEqual([]);
});

test('mobile layout, touch firing, pause and new run', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.screenshot({ path: '/tmp/opencode/null-sector-mobile.png' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.locator('#start').tap();
  await expect(page.locator('#touch-fire')).toBeVisible();
  await page.locator('#touch-fire').tap();
  await expect.poll(async () => Number(await page.locator('#ammo').textContent())).toBeLessThan(30);
  await page.locator('#touch-aim').tap();
  await expect(page.locator('#hud')).toHaveClass(/aiming/);
  await expect(page.locator('#touch-aim')).toHaveAttribute('aria-pressed', 'true');
  await page.locator('#pause-button').tap();
  await expect(page.locator('#modal-title')).toHaveText('SZÜNET');
  await expect(page.locator('#hud')).not.toHaveClass(/aiming/);
  await expect(page.locator('#touch-aim')).toHaveAttribute('aria-pressed', 'false');
  await page.locator('#restart').tap();
  await expect(page.locator('#menu')).toBeVisible();
  await page.locator('#randomize').tap();
  await expect(page.locator('#seed')).not.toHaveValue('');
  await page.locator('#start').tap();
  await expect(page.locator('#health')).toHaveText('100');
  await expect(page.locator('#ammo')).toHaveText('30');
  expect(errors).toEqual([]);
  await context.close();
});

test('aiming supports automatic fire, independent button release and auto reload', async ({ page }) => {
  await page.goto('/');
  await page.locator('#seed').fill('TEST-SECTOR');
  await page.locator('#start').click();
  await expect.poll(() => page.evaluate(() => document.pointerLockElement?.id)).toBe('game');
  await page.mouse.down({ button: 'right' });
  await expect(page.locator('#hud')).toHaveClass(/aiming/);
  await page.waitForTimeout(300);
  await page.screenshot({ path: '/tmp/opencode/null-sector-aim.png' });
  await page.mouse.down({ button: 'left' });
  await expect.poll(async () => Number(await page.locator('#ammo').textContent())).toBeLessThan(27);
  await page.mouse.up({ button: 'right' });
  await expect(page.locator('#hud')).not.toHaveClass(/aiming/);
  const remaining = Number(await page.locator('#ammo').textContent());
  await expect.poll(async () => Number(await page.locator('#ammo').textContent())).toBeLessThan(remaining);
  await expect(page.locator('#reload-status')).toHaveText('ÚJRATÖLTÉS...', { timeout: 15000 });
  await expect(page.locator('#reserve')).toHaveText('90', { timeout: 10000 });
  await expect.poll(async () => Number(await page.locator('#ammo').textContent())).toBeLessThan(29);
  await page.mouse.up({ button: 'left' });
  const stopped = await page.locator('#ammo').textContent();
  await page.waitForTimeout(350);
  await expect(page.locator('#ammo')).toHaveText(stopped);
  await page.mouse.down({ button: 'right' });
  await page.mouse.down({ button: 'left' });
  await page.evaluate(() => document.exitPointerLock());
  await expect(page.locator('#modal')).toBeVisible();
  await expect(page.locator('#hud')).not.toHaveClass(/aiming/);
  await page.mouse.up({ button: 'left' });
  await page.mouse.up({ button: 'right' });
  await page.locator('#resume').click();
  await expect.poll(() => page.evaluate(() => document.pointerLockElement?.id)).toBe('game');
  const resumed = await page.locator('#ammo').textContent();
  await page.waitForTimeout(350);
  await expect(page.locator('#ammo')).toHaveText(resumed);
});
